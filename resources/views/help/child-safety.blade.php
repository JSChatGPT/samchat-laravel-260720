        <h2>Our Commitment</h2>
        <p>
            Samchat has a zero-tolerance policy toward Child Sexual Abuse and Exploitation (CSAE) in any form.
            We do not permit content, behavior, or accounts on our platform that sexualize, endanger, exploit,
            or otherwise cause harm to minors. This applies to all users, on every part of the Samchat service,
            with no exceptions.
        </p>

        <h2>What We Prohibit</h2>
        <p>Samchat strictly prohibits:</p>
        <ul>
            <li>Any imagery, video, text, or material depicting or sexualizing minors</li>
            <li>Grooming, solicitation, or sexual conversations directed at or involving minors</li>
            <li>Sextortion or attempts to coerce a minor into sharing sexual content</li>
            <li>Sharing, requesting, or facilitating access to CSAE material through our service</li>
            <li>Any account created or used to facilitate the above</li>
        </ul>

        <h2>Prevention &amp; Safety Measures</h2>
        <p>To help keep our platform safe, Samchat provides:</p>
        <ul>
            <li>The ability for any user to block another user, immediately preventing further contact</li>
            <li>Account-level enforcement, including suspension or permanent termination of accounts found to violate this policy</li>
            <li>Ongoing review of reports submitted by users regarding abusive behavior</li>
        </ul>

        <h2>Reporting Abuse</h2>
        <p>
            If you encounter content or behavior on Samchat that you believe involves child sexual abuse or
            exploitation, please report it to us immediately. Reports are reviewed promptly, and accounts found
            in violation are removed from the platform.
        </p>
        <div class="contact-box">
            <strong>Report to Samchat:</strong><br>
            Email: <a href="mailto:compliance@samafricaonline.com">compliance@samafricaonline.com</a>
        </div>
        <p>
            If a child is in immediate danger, please also contact your local law enforcement authorities.
            Reports involving suspected CSAE may also be filed with the
            <a href="https://report.cybertip.org/" target="_blank" rel="noopener">National Center for Missing &amp; Exploited Children (NCMEC)</a>
            via CyberTipline.
        </p>

        <h2>Cooperation with Authorities</h2>
        <p>
            Samchat cooperates with law enforcement and relevant regulatory bodies in investigations related to
            CSAE, and where legally required, reports confirmed instances of CSAE material to NCMEC or other
            appropriate authorities.
        </p>

        <h2>Enforcement</h2>
        <p>
            Any account, content, or behavior found to violate this policy will result in immediate content
            removal and account termination, and may be reported to law enforcement and/or NCMEC as required
            by applicable law.
        </p>

